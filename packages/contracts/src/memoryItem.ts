import { z } from 'zod';
import { IsoDateTimeSchema, TraceSchema } from './common.js';

export const MemoryItemTypeSchema = z.enum(['text', 'object', 'scene', 'mixed']);

export const MemoryItemSchema = z.object({
  id: z.string().min(1), // generated by DB layer
  trace: TraceSchema.optional(), // helpful for debugging, optional to store

  type: MemoryItemTypeSchema,
  title: z.string().min(1), // short human label: "Cereal box", "Letter from council"
  content: z.string().min(1), // OCR text summary or extracted content
  tags: z.array(z.string()).default([]),

  createdAt: IsoDateTimeSchema,

  /** Optional: link to stored image/file in storage system */
  mediaRef: z.string().optional(),

  /**
   * Optional: embedding reference for semantic search later.
   * Store as ID to avoid leaking vector format into contracts.
   */
  embeddingRef: z.string().optional(),
});

export type MemoryItem = z.infer<typeof MemoryItemSchema>;
export type MemoryItemType = z.infer<typeof MemoryItemTypeSchema>;
